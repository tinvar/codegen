<?php

declare(strict_types=1);

namespace Tinvar\Codegen;

use Tinvar\Actions\ActionRegistry;
use Tinvar\Auth\PanelRegistry;
use Tinvar\Channels\ChannelRegistry;
use Tinvar\Notifications\InboxRegistry;
use Tinvar\Notifications\NotificationRegistry;
use Tinvar\Data\Data;
use Tinvar\Data\SharedRegistry;
use Tinvar\Discovery\DiscoveredClasses;
use Tinvar\Endpoints\EndpointRegistry;
use Tinvar\Routing\RouteRegistry;
use Tinvar\Transfers\TransferRegistry;

/**
 * `tinvar codegen [--out=DIR] [--check]`: the TypeScript an application's
 * views use, written from its PHP -- what every application's console runs
 * (Tinvar\Console\AppConsole), handed what the application declares.
 *
 *   generated.ts   the Data interfaces, PageProps, a typed route() helper,
 *                  and the endpoints, channels and transfers it declares
 *   modules.d.ts   the ambient `@queries/*` modules
 *   queries.json   which query each `@queries` function calls, which the
 *                  renderer build reads for each route's allowlist
 *   entries.json   each entry point's PHP class, method and file, and what
 *                  the views reach it by: what an editor goes to (ADR 0160)
 *   actions/*.ts   one module of action references per class
 *   testing/       the fakes and mocks component tests run against (ADR 0061)
 *
 * Only a file that changed is written: `tinvar dev` runs this on every
 * save, and a file rewritten as it was is one Vite reloads for nothing.
 * What was generated before and is not now -- a class with no actions
 * left, a query module gone and its mock -- is removed; under testing/,
 * only a file codegen wrote, so a helper a developer put beside the mocks
 * is left, and named.
 *
 * With --check it writes nothing, and fails -- naming each file -- when
 * what is on disk is not what the PHP generates now: the drift guard CI
 * runs.
 */
final readonly class CodegenCommand
{
    /** The line codegen writes first, which marks a file as its own to remove. */
    public const string HEADER = '// Generated by tinvar codegen. Do not edit.';

    /**
     * @param string $out where the files go, unless --out says otherwise
     * @param list<class-string> $payloads Data classes nothing routable reaches: an email's props
     * @param list<class-string> $queries
     * @param list<class-string> $routes the pages and layouts
     * @param list<class-string> $actions
     * @param list<class-string> $fieldEnums sort and filter field enums (#[FieldsOf])
     * @param list<class-string<\Tinvar\Data\SharedData>> $shared the #[Shared] classes
     * @param list<class-string> $endpoints
     * @param list<class-string> $channels
     * @param list<class-string> $transfers
     * @param list<class-string> $notifications
     * @param list<class-string> $inboxes
     * @param PanelRegistry|null $panels the application's panels, which entries.json names an entry point's by its namespace from
     */
    public function __construct(
        private string $out,
        private array $payloads = [],
        private array $queries = [],
        private array $routes = [],
        private array $actions = [],
        private array $fieldEnums = [],
        private array $shared = [],
        private array $endpoints = [],
        private array $channels = [],
        private array $transfers = [],
        private array $notifications = [],
        private array $inboxes = [],
        private ?PanelRegistry $panels = null,
    ) {}

    /**
     * Codegen for what an application registers, as its Kernel's classes()
     * says (ADR 0146): every Data class it has, routable or not, and each
     * entry point and field enum.
     */
    public static function of(string $out, DiscoveredClasses $classes, ?PanelRegistry $panels = null): self
    {
        return new self(
            $out,
            payloads: $classes->payloads,
            queries: $classes->queries,
            routes: $classes->routes,
            actions: $classes->actions,
            fieldEnums: $classes->fieldEnums,
            shared: $classes->shared,
            endpoints: $classes->endpoints,
            channels: $classes->channels,
            transfers: $classes->transfers,
            notifications: $classes->notifications,
            inboxes: $classes->inboxes,
            panels: $panels,
        );
    }

    /** @param list<string> $arguments */
    public function run(array $arguments): int
    {
        $out = $this->out;
        $check = false;
        foreach ($arguments as $argument) {
            if (str_starts_with($argument, '--out=')) {
                $out = rtrim(substr($argument, 6), '/');
            } elseif ($argument === '--check') {
                $check = true;
            } else {
                fwrite(STDERR, "Unknown argument '{$argument}'. Usage: tinvar codegen [--out=DIR] [--check]\n");

                return 64;
            }
        }

        $written = $this->files();

        $stale = array_values(array_filter(
            [...(glob("{$out}/actions/*.ts") ?: []), ...self::generatedUnder("{$out}/testing")],
            static fn (string $file): bool => !isset($written[substr($file, \strlen($out) + 1)]),
        ));
        $handWritten = array_values(array_filter(
            $stale,
            static fn (string $file): bool => str_starts_with($file, "{$out}/testing/") && !self::writtenByCodegen($file),
        ));
        $stale = array_values(array_diff($stale, $handWritten));
        foreach ($handWritten as $file) {
            fprintf(STDERR, "left %s: tinvar codegen did not write it\n", $file);
        }

        if ($check) {
            $drift = [];
            foreach ($written as $name => $contents) {
                $path = "{$out}/{$name}";
                if (!is_file($path) || file_get_contents($path) !== $contents) {
                    $drift[] = is_file($path) ? "{$name} is out of date" : "{$name} is missing";
                }
            }
            foreach ($stale as $file) {
                $drift[] = substr($file, \strlen($out) + 1) . ' is generated from nothing now';
            }
            if ($drift === []) {
                echo "The generated TypeScript matches the PHP signatures.\n";

                return 0;
            }
            fwrite(STDERR, "The generated TypeScript has drifted from the PHP signatures; run tinvar codegen:\n  " . implode("\n  ", $drift) . "\n");

            return 1;
        }

        // A class that no longer has actions leaves no module behind: an
        // import of it should fail the build, not resolve to references the
        // server no longer answers.
        foreach ($stale as $file) {
            unlink($file);
            printf("removed %s\n", $file);
        }
        foreach ($written as $name => $contents) {
            $path = "{$out}/{$name}";
            if (!is_dir(\dirname($path))) {
                mkdir(\dirname($path), 0o755, true);
            }
            $existed = is_file($path) ? file_get_contents($path) : null;
            if ($existed !== $contents) {
                file_put_contents($path, $contents);
            }
            printf("%s %s (%d bytes)\n", $existed === $contents ? 'unchanged' : 'wrote', realpath($path) ?: $path, \strlen($contents));
        }

        return 0;
    }

    /**
     * entries.json names each file from the directory the application's
     * console gives, never from --out: an index written elsewhere -- `tinvar
     * dev --app=` over a copy of an app -- says the same as the app's own,
     * so the copy finds it current.
     *
     * @return array<string, string> path under the output directory => contents
     */
    public function files(): array
    {
        $routes = new RouteRegistry();
        $routes->registerAll($this->routes);
        $actions = new ActionRegistry();
        $actions->registerAll($this->actions);
        $endpoints = new EndpointRegistry();
        $endpoints->registerAll($this->endpoints);
        $channels = new ChannelRegistry();
        $channels->registerAll($this->channels);
        $transfers = new TransferRegistry();
        $transfers->registerAll($this->transfers);

        $files = new TypeScriptGenerator()->files(
            dataClasses: array_values(array_filter($this->payloads, static fn (string $class): bool => is_subclass_of($class, Data::class))),
            queryClasses: $this->queries,
            routes: array_map(RouteTypes::of(...), [...$routes->layouts(), ...$routes->pages()]),
            actions: $actions->all(),
            fieldEnums: $this->fieldEnums,
            shared: $this->shared === [] ? [] : SharedTypes::of(new SharedRegistry($this->shared)),
            endpoints: $endpoints->all(),
            channels: $channels->all(),
            transfers: $transfers->all(),
            notifications: NotificationRegistry::of($this->notifications)->all(),
            inboxes: InboxRegistry::of($this->inboxes)->all(),
        );

        $written = [
            'generated.ts' => $files['module'],
            'modules.d.ts' => $files['ambient'],
            'queries.json' => $files['queries'],
            'entries.json' => new EntryIndex($this->out, $this->panels)->render($routes->layouts(), $routes->pages(), $this->queries, $actions->all(), $endpoints->all()),
        ];
        foreach ($files['actions'] as $class => $contents) {
            $written["actions/{$class}.ts"] = $contents;
        }
        foreach ($files['testing'] as $path => $contents) {
            $written["testing/{$path}"] = $contents;
        }

        return $written;
    }

    /**
     * Whether a file begins with the header codegen writes -- on its first
     * line, or its second under an application's own header line -- and so
     * is codegen's to remove. A symbolic link is never codegen's: it writes
     * files.
     */
    public static function writtenByCodegen(string $file): bool
    {
        if (is_link($file)) {
            return false;
        }
        $handle = @fopen($file, 'r');
        if ($handle === false) {
            return false;
        }
        $lines = [fgets($handle), fgets($handle)];
        fclose($handle);
        foreach ($lines as $line) {
            if (\is_string($line) && rtrim($line, "\r\n") === self::HEADER) {
                return true;
            }
        }

        return false;
    }

    /** @return list<string> every .ts file under $directory, at any depth */
    private static function generatedUnder(string $directory): array
    {
        if (!is_dir($directory)) {
            return [];
        }
        $files = [];
        foreach (new \RecursiveIteratorIterator(new \RecursiveDirectoryIterator($directory, \FilesystemIterator::SKIP_DOTS)) as $file) {
            if ($file instanceof \SplFileInfo && $file->isFile() && str_ends_with($file->getFilename(), '.ts')) {
                $files[] = $file->getPathname();
            }
        }
        sort($files);

        return $files;
    }
}
