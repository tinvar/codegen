<?php

declare(strict_types=1);

/**
 * Everything the generator emits or refuses, beyond the Data basics in
 * TypeScriptGeneratorTest: docblock shapes, unions, queries, routes,
 * actions, and the errors that stop a wrong type being generated.
 */

use Tinvar\Actions\ActionRegistry;
use Tinvar\Codegen\CodegenException;
use Tinvar\Codegen\DocBlock;
use Tinvar\Codegen\RouteTypes;
use Tinvar\Codegen\TypeScriptGenerator;
use Tinvar\Routing\RouteRegistry;
use Tinvar\Tests\Codegen\Fixtures as F;

require_once __DIR__ . '/Fixtures/surface.php';
require_once __DIR__ . '/../../framework/tests/Orm/Fixtures/models.php';

/** The module file, then the ambient one, then each action module. */
function emit(array $data = [], array $queries = [], array $routes = [], array $actions = [], string $header = ''): string
{
    $files = (new TypeScriptGenerator($header))->files($data, $queries, $routes, $actions);

    return implode("\n", [$files['module'], $files['ambient'], ...array_values($files['actions'])]);
}

describe('data shapes', function () {
    it('maps every docblock shape it understands', function () {
        $ts = emit([F\CgPage::class]);

        expect($ts)
            ->toContain('grid: CgSite[][];')
            ->toContain('byPosition: Record<number, CgSite>;')
            ->toContain('labels: Record<string | number, string>;')
            ->toContain('legacy: CgSite[];')
            ->toContain('counts: number[];')
            ->toContain('series: Record<string, number[]>;')
            ->toContain('flags: boolean[];')
            ->toContain('anything: unknown[];')
            ->toContain('nothing: null[];')
            ->toContain('plain: CgSite[];')
            ->toContain('either: string | number;')
            ->toContain('whatever: unknown;')
            ->toContain('maybe: CgSite | null;')
            ->toContain('optional: CgSite[] | null;')
            ->toContain('export interface CgSite {');
    });

    it('puts a header first when given one', function () {
        expect(emit([F\CgSite::class], header: '// header'))->toStartWith("// header\n// Generated by tinvar codegen.");
    });

    it('refuses an intersection type', function () {
        expect(fn () => emit([F\CgIntersection::class]))->toThrow(CodegenException::class, 'intersection');
    });

    it('refuses a Lazy field with no value type', function () {
        expect(fn () => emit([F\CgLazyNoHint::class]))->toThrow(CodegenException::class, 'Lazy');
    });

    it('refuses a name it cannot resolve to a Data object', function () {
        expect(fn () => emit([F\CgUnknownName::class]))->toThrow(CodegenException::class, "Cannot map 'NoSuchThing'");
    });

    // Interfaces are emitted under short names; two classes sharing one
    // became two `export interface CgSite` blocks, merged by TypeScript.
    it('refuses two Data classes that would share an interface name', function () {
        expect(fn () => emit([F\CgSite::class, F\Elsewhere\CgSite::class]))
            ->toThrow(CodegenException::class, 'would both be emitted as `CgSite`');
    });
});

describe('queries', function () {
    it('types a batch query by its loadMany element and its declared arguments', function () {
        expect(emit(queries: [F\FindSite::class]))
            ->toContain("declare module '@queries/sites' {")
            ->toContain('export function find(args: { site: string }): Promise<CgSite>;');
    });

    // An untyped parameter allows null, so QueryRegistry does not require it.
    it('types a plain query by its __invoke, untyped parameters as unknown', function () {
        expect(emit(queries: [F\SearchSites::class]))
            ->toContain('export function searchSites(args: { term: string; limit: number; untyped?: unknown }): Promise<CgSite>;');
    });

    // tinvar-spec.md's RackStats takes a Rack. It was refused -- "Cannot map
    // 'Racks\Models\Rack'" -- though a model argument crosses as its key,
    // as a batch query's declared arguments already did.
    it('types a model parameter of a plain query as its key', function () {
        expect(emit(queries: [F\SiteStats::class]))
            ->toContain('export function stats(args: { site: string; rack?: string | null }): Promise<CgSite>;');
    });

    // QueryRegistry lets a caller leave out a parameter with a default, or
    // one that allows null; typed as required, every call had to pass them.
    it('types a parameter a caller may leave out as optional', function () {
        expect(emit(queries: [F\SearchWithOptions::class]))
            ->toContain('export function search(args: { term: string; limit?: number; region?: string | null; floor?: number | null }): Promise<CgSite>;');
    });

    // `array` says nothing of what is in it; the docblock does, as it does
    // for a batch query's loadMany().
    it('types a list result from the @return docblock of __invoke', function () {
        expect(emit(queries: [F\AllSites::class]))
            ->toContain('export function all(args: {  }): Promise<CgSite[]>;');
    });

    // Every query went into '@queries/racks', the example app's name.
    it('groups queries by their own prefix, not a fixed module', function () {
        $ts = emit(queries: [F\FindSite::class, F\Ping::class]);

        expect($ts)
            ->toContain("declare module '@queries' {\n  /** Calls the PHP query `ping`")
            ->toContain("declare module '@queries/sites' {")
            ->not->toContain('@queries/racks');
    });

    it('refuses a class without #[Query]', function () {
        expect(fn () => emit(queries: [F\NotAQuery::class]))->toThrow(CodegenException::class, 'no #[Query]');
    });

    it('refuses a query whose result cannot be typed', function (string $class, string $message) {
        expect(fn () => emit(queries: [$class]))->toThrow(CodegenException::class, $message);
    })->with([
        'no return type' => [F\UntypedReturn::class, 'needs a return type'],
        'loadMany without @return' => [F\UndocumentedBatch::class, '@return list<SomeData>'],
    ]);
});

describe('routes', function () {
    $routes = function (): array {
        $registry = new RouteRegistry();
        $registry->registerAll([F\SitesLayout::class, F\RackPage::class, F\AboutPage::class, F\RawPage::class]);

        return array_map(RouteTypes::of(...), [...$registry->layouts(), ...$registry->pages()]);
    };

    it('reads the loader return type as the route data, and none without a loader or Data', function () use ($routes) {
        $byView = [];
        foreach ($routes() as $route) {
            $byView[$route->view] = $route->dataClasses;
        }

        expect($byView['sites/rack'])->toBe([F\CgPage::class])
            ->and($byView['sites/layout'])->toBe([F\CgSite::class])
            ->and($byView['sites/about'])->toBe([])
            ->and($byView['sites/raw'])->toBe([]);
    });

    it('emits page, layout and named-route maps', function () use ($routes) {
        $ts = emit(routes: $routes());

        expect($ts)
            ->toContain("'sites/rack': CgPage;")
            ->toContain("'sites/about': null;")
            ->toContain("'sites/rack': { site: string; rack: string };")
            ->toContain("'sites/about': Record<string, never>;")
            ->toContain('export type PageProps<V extends keyof PageDataMap>')
            ->toContain('export interface LayoutDataMap {')
            ->toContain('export type LayoutProps<K extends keyof LayoutDataMap>')
            ->toContain("'sites.rack': { site: string; rack: string };")
            ->toContain("'sites.raw': Record<string, never>;")
            ->toContain("import { routes } from '@tinvar/react/route';")
            ->toContain('export const route = routes<RouteMap>({')
            ->toContain("  'sites.rack': ['sites', '{site}', 'racks', '{rack}'],\n")
            ->toContain("  'sites.raw': ['sites', 'raw'],\n");
    });

    it('emits no route maps without routes', function () {
        expect(emit([F\CgSite::class]))->not->toContain('PageDataMap')->not->toContain('RouteMap');
    });
});

describe('actions', function () {
    it('types an action by its model ids and form-request fields', function () {
        $registry = new ActionRegistry();
        $registry->register(F\SiteActions::class);

        $files = (new TypeScriptGenerator())->files([], [], [], $registry->all());

        expect($files['module'])->toContain('export interface ActionResult {')
            ->and(array_keys($files['actions']))->toBe(['SiteActions'])
            ->and($files['actions']['SiteActions'])
            ->toContain("import { action } from '@tinvar/react/action';")
            ->toContain("import type { ActionResult } from '../generated';")
            ->toContain("export const rename = action<{ site: string; name: string; priority: number | null }, ActionResult>('SiteActions.rename');")
            ->and($files['ambient'])->not->toContain('@actions');
    });

    // A reference is a value, handed to <Form> and called: a declaration of
    // a function nothing defined failed the build on its first import.
    it('writes a real module per class rather than declaring one', function () {
        $registry = new ActionRegistry();
        $registry->register(F\SiteActions::class);

        expect((new TypeScriptGenerator())->files([], [], [], $registry->all())['actions']['SiteActions'])
            ->not->toContain('declare');
    });

    // "Uploaded files are referenced only by a server-issued upload ticket":
    // what crosses is the reference /_upload answered with, a string.
    it('types an upload parameter as the reference a form sends, optional where the parameter is', function () {
        require_once __DIR__ . '/../../framework/tests/Uploads/Fixtures/app.php';
        $registry = new ActionRegistry();
        $registry->register(\Tinvar\Tests\Uploads\Fixtures\ProfileActions::class);

        expect((new TypeScriptGenerator())->files([], [], [], $registry->all())['actions']['ProfileActions'])
            ->toContain("export const avatar = action<{ profile: string; avatar: string }, ActionResult>('profiles.avatar');")
            ->toContain("export const document = action<{ profile: string; document?: string }, ActionResult>('profiles.document');");
    });

    it('imports the module file by its path from the actions directory', function () {
        $registry = new ActionRegistry();
        $registry->register(F\SiteActions::class);

        expect((new TypeScriptGenerator(module: '../types/app'))->files([], [], [], $registry->all())['actions']['SiteActions'])
            ->toContain("from '../../types/app';");
    });
});

describe('docblock reading', function () {
    it('takes the named @param, else the sole @var, else nothing', function () {
        expect(DocBlock::typeFor("/** @param list<int> \$a\n @param string \$b */", 'b'))->toBe('string')
            ->and(DocBlock::typeFor('/** @var list<int> */'))->toBe('list<int>')
            ->and(DocBlock::typeFor('/** nothing */', 'a'))->toBeNull()
            ->and(DocBlock::typeFor(false))->toBeNull()
            ->and(DocBlock::typeFor(''))->toBeNull();
    });

    it('reads @return, and nothing from an empty docblock', function () {
        expect(DocBlock::returnType('/** @return list<int> */'))->toBe('list<int>')
            ->and(DocBlock::returnType(false))->toBeNull()
            ->and(DocBlock::returnType(''))->toBeNull()
            ->and(DocBlock::returnType('/** no tag */'))->toBeNull();
    });

    it('splits map keys without cutting inside generics', function () {
        expect(DocBlock::elementType('array<string, array<int, int>>'))->toBe(['key' => 'string', 'value' => 'array<int, int>'])
            ->and(DocBlock::elementType('int'))->toBeNull()
            ->and(DocBlock::elementType(null))->toBeNull()
            ->and(DocBlock::lazyType(null))->toBeNull()
            ->and(DocBlock::lazyType('Lazy<int>'))->toBe('int');
    });
});
